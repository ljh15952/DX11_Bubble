// ============================================================================
//  Transform.h
//    위치와 방향. 값 타입이고 아무것도 상속하지 않는다.
//
//  ---- ★ 왜 컴포넌트가 아닌가 ----
//    Unity 도 Transform 만은 컴포넌트로 두지 않고 GameObject 에 내장한다.
//
//      컴포넌트로 만들면  ->  모든 컴포넌트가 Get<Transform>() 을 하고
//                            nullptr 검사를 해야 한다.
//                            「위치가 없는 엔티티」는 존재하지 않는데도.
//      내장하면          ->  transform 은 항상 있다. 검사가 전부 사라진다.
//
//    **「반드시 있는 것」은 옵션으로 만들지 않는다.**
//    이것이 「무엇을 컴포넌트로 뺄까」를 판단하는 첫 번째 기준이다.
// ============================================================================
#pragma once

struct Transform
{
    // 캔버스(640x360) 좌표. 원점은 **발밑 가운데**다.
    //
    // ★ y 는 지금 「깊이」처럼 쓰이지만, 플랫포머 전환(design.md §3.8) 이후에는
    //   「높이」가 된다. 의미가 바뀌어도 이 구조체는 안 바뀐다 —
    //   해석하는 쪽(BodyComponent)이 달라질 뿐이다.
    float x = 0.0f;
    float y = 0.0f;

    // +1 = 오른쪽, -1 = 왼쪽.
    // 스프라이트 반전과 공격 히트박스 방향이 둘 다 이것을 본다.
    int facing = 1;
};
