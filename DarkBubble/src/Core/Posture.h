// ============================================================================
//  Posture.h
//    자세 — 서기 / 웅크리기 / 엎드리기.
//
//  ---- ★ 왜 엔진(Core)에 있는가 ----
//    처음에는 PartsComponent(게임) 안에 있었다. 피격 상자를 고르는 데만 썼기
//    때문이다. 그런데 **지형 상자도 자세를 따라간다** — 웅크리면 낮은 틈을
//    지나가고, 엎드리면 더 낮다.
//
//    §9 의 규칙 그대로다: **두 번째 사용자가 생기면 엔진으로 올린다.**
//
//  ---- ★★ bool 이 아닌 이유 ----
//    한동안 `SetCrouching(bool)` 이었다. 자세가 둘일 때는 맞았는데,
//    엎드리기가 생기자 **bool 로는 표현할 수 없는 세 번째 값**이 되었다.
//    그래서 엎드린 몸이 「서 있는 크기」로 남았고, 아무도 눈치채지 못했다 —
//    bool 은 언제나 둘 중 하나를 정확히 답하기 때문이다.
//
//    경우가 둘에서 셋이 되면 bool 과 `? :` 를 버리고 enum 과 `switch` 로 간다.
//    그래야 네 번째가 생겼을 때 **컴파일러가 빠진 곳을 짚어 준다.**
// ============================================================================
#pragma once

enum class Posture
{
    Stand,
    Crouch,   // 웅크리기. 키를 누르는 동안 (지상 전용)
    Prone,    // 엎드리기. 다리가 부서지면 (선택이 아니다)
};
