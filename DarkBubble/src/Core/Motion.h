// ============================================================================
//  Motion.h
//    시간에 따라 움직이는 방식을 담은 작은 수식들. 상태를 갖지 않는다.
//
//  ---- ★ 왜 컴포넌트가 아니라 자유 함수인가 ----
//    「감속하며 미끄러진다」는 **계산**이지 **가진 것**이 아니다.
//    데이터도 수명도 없으므로 컴포넌트로 만들 이유가 없다.
//
//    공유해야 하는 것은 공식뿐이고, 「어디로 얼마나」는 부르는 쪽이 안다.
//    필요한 부분만 올리면 쓰는 쪽이 자유로워진다 —
//    통째로 컴포넌트로 만들었다면 플레이어의 구르기와 적의 넉백이
//    같은 상태 저장소를 공유해야 했을 것이다.
// ============================================================================
#pragma once

// ----------------------------------------------------------------------------
//  DecayingStep — 남은 틱에 비례해 감속하는 이동량
//
//    일정 속도로 움직이면 어색하다. 초반에 빠르고 끝에서 감속해야
//    구르기도 넉백도 그럴듯해 보인다. 카메라 흔들림 감쇠와 같은 발상이다.
//
//      속도
//       │▓▓▓▓▓▓
//       │▓▓▓▓
//       │▓▓
//       └────────→ 틱
//
//    ★ 가중치의 합이 distance 와 정확히 같아지도록 정규화한다.
//      1 + 2 + ... + n = n(n+1)/2 이므로 그것으로 나눈다.
//      정규화하지 않으면 틱 수를 바꿀 때마다 총 이동 거리가 따라 변한다.
//
//    elapsedTicks 는 **1부터** 세는 값이다(상태에 들어간 뒤 흐른 틱).
//    상태 머신이 ++m_stateTicks 를 먼저 하므로 자연스럽게 그렇게 된다.
// ----------------------------------------------------------------------------
inline float DecayingStep(int elapsedTicks, int totalTicks, float distance)
{
    if (totalTicks <= 0)
        return 0.0f;

    const int remaining = totalTicks - elapsedTicks + 1;   // total .. 1
    if (remaining <= 0)
        return 0.0f;

    const float weightSum = static_cast<float>(totalTicks) * (totalTicks + 1) * 0.5f;
    return distance * static_cast<float>(remaining) / weightSum;
}
