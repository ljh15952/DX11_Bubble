// ============================================================================
//  Animation.h
//    스프라이트시트에서 프레임을 골라 시간에 따라 넘긴다.
//
//    시트 배치 규칙: 한 줄(row) = 하나의 애니메이션, 한 칸(column) = 한 프레임.
//
//      sheet.png (256×128)
//         0    64   128  192  256
//       0 ┌────┬────┬────┬────┐
//         │ 0  │ 1  │ 2  │ 3  │  row 0 = idle
//      64 ├────┼────┼────┼────┤
//         │ 0  │ 1  │ 2  │ 3  │  row 1 = run
//     128 └────┴────┴────┴────┘
// ============================================================================
#pragma once

#include <windows.h>

// ----------------------------------------------------------------------------
//  AnimationClip — "무엇을" 재생할지. 데이터. 나중에 JSON 으로 빠질 부분.
// ----------------------------------------------------------------------------
struct AnimationClip
{
    int  row           = 0;      // 시트의 몇 번째 줄
    int  frameCount    = 1;      // 프레임 수
    int  ticksPerFrame = 6;      // 한 프레임을 몇 틱 보여줄까 (60 / n = 애니메이션 fps)
    bool loop          = true;
};


// ----------------------------------------------------------------------------
//  AnimationPlayer — "지금 어디까지" 재생했는지. 상태.
//
//    클립(데이터)과 재생 상태를 나눠 둔 이유:
//    같은 idle 클립을 플레이어와 적 10 마리가 공유하되,
//    각자 다른 프레임을 보고 있을 수 있어야 한다.
// ----------------------------------------------------------------------------
class AnimationPlayer
{
public:
    // 클립을 지정한다.
    // ★ 이미 같은 클립을 재생 중이면 아무것도 하지 않는다.
    //   이 판정이 없으면, 매 틱 Play() 를 부르는 코드에서
    //   프레임이 계속 0 으로 되돌아가 애니메이션이 멈춘 것처럼 보인다.
    //   (직접 겪으면 원인을 찾기 매우 어려운 종류의 버그다)
    void Play(const AnimationClip& clip, bool forceRestart = false);

    // 1 틱 진행. Update 안에서 틱마다 정확히 한 번 호출한다.
    void Tick();

    // 지금 프레임에 해당하는 소스 사각형.
    // right / bottom 은 배타적이므로 left + cellW 가 맞다. (left + cellW - 1 이 아니다)
    RECT SourceRect(int cellW, int cellH) const;

    int  Frame()    const { return m_frame; }
    bool Finished() const { return m_finished; }   // loop = false 인 클립이 끝났는가

private:
    AnimationClip m_clip;
    int  m_frame    = 0;   // 지금 몇 번째 칸을 보여주는가
    int  m_tick     = 0;   // 이 칸을 몇 틱째 보여주고 있는가
    bool m_finished = false;
};
