// ============================================================================
//  WeaponType.h
//    무기 **한 종류**가 들고 다니는 것 전부 + weapons.json 읽기.
//
//  ---- ★ Moveset 에서 이름이 바뀌었다 (8-a) ----
//    「무브셋」은 **공격 묶음**이라는 뜻이었다. 무기가 하나뿐일 때는 그것이
//    곧 무기였지만, 둘이 되는 순간 무기는 공격 말고도 들고 다닐 것이 생긴다 —
//    이름 · 아이콘 · 양손인가.
//
//    ★ 이름을 바꿨으므로 옛 사용처가 전부 컴파일 에러가 된다(handoff §9.1).
//
//  ---- ★★ 맨손은 **무기가 아니다** ----
//    전에는 물기 셋(bite / biteCrouch / biteProne)이 Moveset 안에 있었다.
//    무기가 하나일 때는 안 틀렸지만, 카탈로그가 되는 순간 **무기마다 이빨을
//    한 벌씩** 들고 있게 된다 — 같은 값이 N 곳에 있는 것이고, 대검의 이빨과
//    단검의 이빨이 달라지는 사고가 난다.
//
//    「그 손에 무기가 없을 때」는 **몸의 성질**이지 무기의 성질이 아니다.
//    그래서 UnarmedSet 은 따로 있고 컨트롤러가 **하나만** 들고 있다.
//
//  ---- ★ 카탈로그인 이유는 적과 같다 ----
//    주소가 안정해야 한다. `m_currentAttack == &Weapon().light` 로
//    「직전에 기본 공격을 냈는가」를 묻기 때문이다(§3.2.1).
//    리로드는 **원소의 값만 덮어쓸 뿐** 노드를 새로 만들지 않는다.
//    ※ 그래서 `std::map` 이다. `vector` 면 재배치할 때 주소가 바뀐다.
// ============================================================================
#pragma once

#include <map>
#include <string>

#include "Gameplay/AttackData.h"

// ============================================================================
//  WeaponType — 무기 하나
// ============================================================================
struct WeaponType
{
    // 화면에 뜨는 이름. ★ ASCII 만 — BitmapFont 가 ASCII 전용이다.
    //   ※ `AttackData::name` 이 `const char*` 인 것과 다르다. 저것은 코드의
    //     리터럴을 가리키는 **식별자**라 파일에서 안 읽는다.
    //     이쪽은 무기를 추가할 때 **파일에 적는 값**이므로 문자열을 소유해야 한다.
    std::string name = "DAGGER";

    // icons.png 의 칸 번호. ★ 코드에 `if (단검) … else if (대검) …` 을 쓰지
    //   않기 위한 것이다 — 무기를 추가할 때 고칠 곳이 파일 하나로 끝난다.
    int icon = 1;

    // ★★ 두 손을 다 쓰는가. §1.2 의 기회비용이 **슬롯 구조만으로** 성립한다 —
    //   양손 무기를 들면 왼손이 막히고, 그러면 나중에 횃불도 방패도 못 든다.
    //   규칙을 따로 쓸 필요가 없다(design.md §3.10).
    //
    //   ★ 그리고 §3.2.2 가 저절로 무거워진다: 양손 무기는 **어느 팔이 잘려도**
    //     떨어진다. 한 손 무기는 그 손의 팔만 본다.
    bool twoHanded = false;

    // 무기 공격 여섯. ★ 어느 것이 나갈지는 **자세와 직전 상태**가 정한다
    //   (PlayerController::SelectAttack).
    AttackData light{};    // 기본
    AttackData crouch{};   // 웅크려서 — 다리를 노린다
    AttackData dash{};     // 구르기 직후에만
    AttackData thrust{};   // 기본 공격 뒤 2타 — 머리
    AttackData jump{};     // 공중에서 내려찍기
    AttackData prone{};    // 엎드려서

    // ========================================================================
    //  ★★ 방패 (design.md §3.11)
    //
    //    ★ **방패를 따로 만들지 않았다.** 손 슬롯이 「이름 하나」라, 목록이
    //      둘이면 슬롯이 **어느 목록을 가리키는지**부터 물어야 한다.
    //      MapInteract 에 포탈과 화톳불을 같이 둔 것과 같은 판단이다 —
    //      안 쓰는 칸이 남는 것은 구조를 두 벌 만드는 것보다 훨씬 싸다.
    //
    //    ★★ 「방패인가」라는 칸도 **없다.** 막는 띠가 있으면 방패다 —
    //      플래그와 값이 따로 있으면 둘이 어긋나는 상태가 생긴다.
    // ========================================================================

    // 덮는 띠. 발끝 기준, **선 자세**의 값이다.
    //   ★ 자세가 낮아지면 **같이 내려간다**(몸 높이 비율로 줄인다).
    //     그래서 「앉으면 하단을 막는다」에 특수 규칙이 필요 없다 —
    //     높은 곳이 비고 낮은 곳이 덮이는 것이 좌표만으로 성립한다.
    //
    //     37~55 상단 / 26~36 중단 / 2~20 하단
    float guardTop    = 0.0f;
    float guardBottom = 0.0f;

    // 몸 앞으로 내미는 거리. 공격 상자와 겹쳐야 막힌다.
    float guardReach  = 16.0f;

    // 막아 내는 **비율(%)**. 100 이면 무피해.
    //   ★ 고정값이 아니라 비율인 이유: 고정값이면 약한 공격을 완전히 지우고
    //     강한 공격에는 무의미해진다. 비율은 **어느 세기에서도 같은 뜻**이다.
    int   defense     = 0;

    // 막는 데 드는 스태미나 = 공격의 impact × 이 값 / 100.
    //   ★★ `defense` 와 **짝**이다. 큰 방패는 많이 막아 주는 대신 비싸다 —
    //     숫자 둘이 §3.10 의 「강해지는 대신 무엇을 포기하는가」 한 줄이 된다.
    //   ★ 스태미나가 바닥나면 `Depleted` → `Exhausted` 로 경직한다.
    //     **가드 브레이크를 따로 안 만들어도** 「막다 보면 못 막는다」가 나온다.
    int   guardCost   = 100;

    // 단단함. **이것 이상의 impact 는 못 튕긴다** (§3.12).
    //   ★ 공격의 `impact` 와 같은 눈금이다. 새 단위를 만들지 않는다 —
    //     강인도(poise)가 「버틴다/휘청인다」를 impact 하나로 정하는 것과
    //     **완전히 같은 모양**이다.
    //   ★★ 막히기만 하는 것과 튕겨 내는 것의 차이가 여기서 나온다:
    //     단단함 >= impact  → **친 쪽이 튕긴다**(경직) — 반격할 틈이 생긴다
    //     그 외             → 막기만 한다
    //   가드 브레이크는 여기서 정하지 않는다 — 스태미나가 이미 맡고 있다(§3.11.1).
    int   hardness    = 0;

    // 방어 자세 그림. ★ 무기의 `clip` 과 같은 자리다 — 무기가 자기 그림을
    //   들고 다니므로, 방패를 추가할 때 C++ 을 고칠 일이 없다.
    AnimationClip guardClip      { /*row*/ 21, /*frames*/ 2, /*ticks*/ 12, /*loop*/ true };
    AnimationClip guardCrouchClip{ /*row*/ 22, /*frames*/ 2, /*ticks*/ 12, /*loop*/ true };

    // 막는 띠가 있으면 방패다.
    bool IsShield() const { return guardTop > guardBottom; }
};


// ============================================================================
//  UnarmedSet — 맨손 (§3.2.2.1)
//
//    ★ 무기가 없을 때 남는 것. **무기 카탈로그 바깥**에 있다 —
//      위의 「맨손은 무기가 아니다」 참조.
// ============================================================================
struct UnarmedSet
{
    AttackData bite{};
    AttackData biteCrouch{};
    AttackData biteProne{};
};


using WeaponCatalog = std::map<std::string, WeaponType>;


namespace WeaponIO
{
    // ------------------------------------------------------------------------
    //  LoadInto — 파일의 값으로 **덮어쓴다**
    //
    //    성공하면 true 이고 out / unarmed 가 갱신된다.
    //    ★ 실패하면 **둘 다 건드리지 않고** false 를 돌려준다 —
    //      다른 로더들과 같은 약속이다(MapIO / EnemyTypeIO).
    //      되돌리는 책임을 부르는 쪽에 두면 언젠가 한 곳이 빠뜨린다.
    //
    //    ★★ `base` 는 **없던 무기가 출발하는 값**이다. 빈 WeaponType 에서
    //      시작하면 파일에 안 적은 항목이 AttackData 의 일반 기본값이 되어
    //      「무기를 하나 더 적었더니 이상한 것이 나왔다」가 된다 —
    //      적 카탈로그가 DefaultGrunt 에서 출발하는 것과 같은 이유다.
    //      그래서 대검은 **단검과 다른 것만** 적으면 된다.
    // ------------------------------------------------------------------------
    bool LoadInto(const wchar_t* path, WeaponCatalog& out, UnarmedSet& unarmed,
                  const WeaponType& base, std::string* error);
}
