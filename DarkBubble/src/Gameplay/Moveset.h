// ============================================================================
//  Moveset.h
//    무기 하나가 들고 다니는 공격들 + 그것을 파일에서 읽어 오는 일.
//
//  ---- ★ C++ 상수가 없어진 것이 아니다. **기본값**이 되었다 ----
//    PlayerController.cpp 의 kDaggerLight 같은 값들은 그대로 남는다.
//    JSON 은 그 위에 **덮어쓰는** 것이고, 파일이 없거나 깨져도 게임은 돈다.
//
//    그래서 이 구조에서는 다음이 전부 성립한다:
//      · 파일을 지워도 실행된다
//      · 키를 몇 개만 적어도 나머지는 기본값이 된다
//      · 오타가 나면 **옛 값 그대로** 두고 로그만 남는다
//
//    ★ 「고치다 오타가 나면 게임이 죽는다」가 되면 아무도 핫 리로드를 안 쓴다.
//      리로드의 값어치는 **틀려도 안전하다**는 데서 나온다.
//
//  ---- ★★ 이름(name)은 덮어쓰지 않는다 ----
//    AttackData::name 은 `const char*` 이고 리터럴을 가리킨다.
//    JSON 의 문자열로 바꾸려면 그 문자열을 **누군가 계속 들고 있어야** 하는데,
//    파서가 만든 임시를 가리키게 두면 그 순간 댕글링이다.
//
//    그리고 이름은 **조정하는 값이 아니라 식별자**다. 숫자를 만지려고 파일을
//    뺀 것이지 공격을 새로 만들려는 것이 아니다 — 새 무기는 8단계의 몫이다.
// ============================================================================
#pragma once

#include <string>

#include "Gameplay/AttackData.h"

// ============================================================================
//  Moveset — 단검 하나의 공격 전부
//
//    ★ 포인터 비교가 계속 동작해야 한다. `m_currentAttack == &moves.light` 로
//      「직전에 기본 공격을 냈는가」를 묻고 있기 때문이다(§3.2.1).
//      그래서 이 구조체는 **컨트롤러가 값으로 소유**한다 — 주소가 안 변한다.
//      리로드는 필드를 덮어쓸 뿐이라 주소가 유지된다.
// ============================================================================
struct Moveset
{
    // 무기 공격
    AttackData light;      // 기본
    AttackData crouch;     // 웅크려서 — 다리를 노린다
    AttackData dash;       // 구르기 직후에만
    AttackData thrust;     // 기본 공격 뒤 2타 — 머리
    AttackData jump;       // 공중에서 내려찍기
    AttackData prone;      // 엎드려서

    // 맨손 — 그 손에 무기가 없을 때(§3.2.2.1)
    AttackData bite;
    AttackData biteCrouch;
    AttackData biteProne;
};


namespace MovesetIO
{
    // ------------------------------------------------------------------------
    //  LoadInto — 파일의 값으로 **덮어쓴다**
    //
    //    성공하면 true 이고 out 이 갱신된다.
    //    ★ 실패하면 **out 을 건드리지 않고** false 를 돌려준다 —
    //      부르는 쪽이 「실패했으니 되돌려야지」를 신경 쓸 필요가 없다.
    //      되돌리는 책임을 부르는 쪽에 두면 언젠가 한 곳이 빠뜨린다.
    //
    //    error 에는 줄·칸이 붙은 메시지가 들어간다.
    // ------------------------------------------------------------------------
    bool LoadInto(const wchar_t* path, Moveset& out, std::string* error);
}
