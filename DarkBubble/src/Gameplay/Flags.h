//    세상의 기억 — 플래그 (10-b, design.md §6.5.2).
//
//  ---- ★ 플래그 = 세상이 기억하는 사실 하나에 붙인 이름 ----
//    「종류:이름」 모양의 글 하나가 사실 하나다. **있거나 없거나** 둘뿐이다.
//
//      chest:field:torch   들판의 torch 상자를 열었다       ← 상자가 세운다
//      met:pilgrim         순례자의 말을 끝까지 들었다      ← npcs.json 의 sets 가 세운다
//
//    ★ 숫자(몇 번 만났나)는 없다. 필요해지면 그때 — 지금 쓰는 곳이 없다.
//
//  ---- ★★ 열린 상자가 여기로 합쳐졌다 ----
//    8-h 의 「열린 상자」(PlayScene::m_openedChests)는 이미 「맵:id」 이름의 목록이라
//    **생김새가 플래그와 같았다.** 따로 두면 NPC 의 조건이 상자를 보려 할 때
//    **두 곳을 물어야** 한다 — 「횃불을 찾았구나」 같은 대사가 그것이다.
//    기억하는 곳이 하나면 조건도 하나를 묻는다.
//
//  ---- 쉬어도 · 죽어도 · 껐다 켜도 남는다 ----
//    부활(Respawn)도 휴식(Rest)도 건드리지 않고, 저장(9)에 들어간다.
//    ★ set 이라 **정렬되어** 나온다 → 같은 기억이면 같은 저장 글이 된다
//      (Autosave 의 「글끼리 비교」가 여기에 기댄다).
// ============================================================================
#pragma once

#include <set>
#include <string>

using FlagSet = std::set<std::string>;

// 상자 하나의 플래그. ★ 만드는 곳을 **하나로** 둔다 — 상자를 열 때 · 열렸는지
//   물을 때 · 옛 저장(판 1)을 옮길 때가 전부 이 모양을 써야 한다. 셋이 따로
//   글자를 이어 붙이면 언젠가 하나만 `:` 를 빠뜨린다.
inline std::string ChestFlag(const std::string& map, const std::string& chestId)
{
    return "chest:" + map + ":" + chestId;
}
